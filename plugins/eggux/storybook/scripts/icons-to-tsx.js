#!/usr/bin/env node
// Writes src/components/icons/index.tsx from icons/iconmcp.json (the EGG UI icon set, drawn by
// IconMCP, MIT). Each entry is keyed by the Figma name (Icon/<name>) and holds the IconMCP SVG
// (outline, stroke 1, radius 0, 16-unit grid). Components are named in PascalCase (trash-2 →
// Trash2) and draw a 1 px line at every size (non-scaling stroke), like the Figma icons.
// Usage: node scripts/icons-to-tsx.js [icons/iconmcp.json] > src/components/icons/index.tsx
import { readFileSync } from 'node:fs';

const file = process.argv[2] || 'icons/iconmcp.json';
const data = JSON.parse(readFileSync(file, 'utf8'));

const pascal = (name) =>
  name
    .split('-')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

const inner = (svg) => {
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error('not an svg');
  return m[1].replace(/\s*\n\s*/g, '').trim();
};

const names = Object.keys(data).sort();
const lines = [];
lines.push('// Generated by scripts/icons-to-tsx.js from icons/iconmcp.json. Do not edit by hand.');
lines.push('// Icons: IconMCP (https://iconmcp.com, MIT), outline, stroke 1, radius 0, 16-unit grid.');
lines.push("import * as React from 'react';");
lines.push('');
lines.push("export type IconProps = Omit<React.SVGProps<SVGSVGElement>, 'children'> & {");
lines.push('  /** Width and height in px or any CSS length. Default 24; a `size-*` class wins. */');
lines.push('  size?: number | string;');
lines.push('};');
lines.push('');
lines.push('export type Icon = React.FC<IconProps> & { iconName: string };');
lines.push('');
lines.push('function create(iconName: string, body: string): Icon {');
lines.push('  const Component = ({ size = 24, strokeWidth = 1, className, ...props }: IconProps) => (');
lines.push('    <svg');
lines.push('      xmlns="http://www.w3.org/2000/svg"');
lines.push('      viewBox="0 0 16 16"');
lines.push('      width={size}');
lines.push('      height={size}');
lines.push('      fill="none"');
lines.push('      stroke="currentColor"');
lines.push('      strokeWidth={strokeWidth}');
lines.push('      strokeLinecap="round"');
lines.push('      strokeLinejoin="round"');
lines.push('      aria-hidden="true"');
lines.push('      data-icon={iconName}');
lines.push("      className={className ? `egg-icon ${className}` : 'egg-icon'}");
lines.push('      {...props}');
lines.push('      dangerouslySetInnerHTML={{ __html: body }}');
lines.push('    />');
lines.push('  );');
lines.push('  Component.displayName = iconName;');
lines.push('  return Object.assign(Component, { iconName });');
lines.push('}');
lines.push('');

const missing = [];
for (const name of names) {
  const entry = data[name];
  if (!entry || !entry.svg) {
    missing.push(name);
    continue;
  }
  const source = entry.iconmcp && entry.iconmcp !== name ? ` (IconMCP ${entry.iconmcp})` : '';
  lines.push(`/** Figma Icon/${name}${source} */`);
  lines.push(`export const ${pascal(name)} = create('${name}', ${JSON.stringify(inner(entry.svg))});`);
}
lines.push('');
lines.push('/** Every icon by its Figma name (Icon/<name>). */');
lines.push('export const icons = {');
for (const name of names) if (!missing.includes(name)) lines.push(`  '${name}': ${pascal(name)},`);
lines.push('} as const;');
lines.push('');
lines.push('export type IconName = keyof typeof icons;');
process.stdout.write(lines.join('\n') + '\n');
if (missing.length) process.stderr.write(`no svg for: ${missing.join(', ')}\n`);
